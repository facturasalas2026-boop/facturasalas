-- ============================================================
-- ALAS · Control de Facturas — Registro de entregas (pickeo)
-- Proyecto Supabase DEDICADO: peusrhpqatobkjwwgmub
-- Correr en el SQL Editor.
--
-- Cada factura física trae un código de barra = número de ENTREGA.
-- El operador lo escanea y se registra con fecha/hora y usuario.
-- La entrega es ÚNICA para siempre: si se re-escanea, la UI muestra
-- una alerta roja ("ya ha sido registrada"). El UNIQUE de acá es la
-- garantía real (atrapa incluso a dos usuarios registrando a la vez).
--
-- La anon key es pública por diseño; el gate real es el SSO ALAS.
-- NUNCA usar service_role en el cliente.
-- ============================================================

create table if not exists registro_entregas (
  id                bigint generated by default as identity primary key,
  entrega           text        not null,             -- código de barra (normalizado: TRIM + MAYÚSCULAS)
  estado            text        not null default 'REGISTRADO',
  registrado_por    text,                              -- nombre del usuario (AlasAuthClient)
  registrado_por_id text,                              -- id del usuario si está disponible
  created_at        timestamptz not null default now(),
  constraint registro_entregas_entrega_key unique (entrega)
);

create index if not exists idx_registro_entregas_created
  on registro_entregas (created_at desc);

-- ── RLS: lectura/escritura anon (el control fino lo hace el SSO en la UI) ──
alter table registro_entregas enable row level security;

drop policy if exists anon_all on registro_entregas;
create policy anon_all on registro_entregas
  for all to anon using (true) with check (true);

grant usage on schema public to anon, authenticated;
grant all on registro_entregas to anon, authenticated;
grant all on all sequences in schema public to anon, authenticated;

-- ── (Opcional) Realtime: para que varios pickers vean los registros en vivo ──
-- Si el publication ya existe, este alter agrega la tabla; si ya está, ignorá el error.
do $$
begin
  begin
    alter publication supabase_realtime add table registro_entregas;
  exception when duplicate_object then null;
           when undefined_object then null;
  end;
end $$;
